"""Monthly client and inbound counter reset, scheduled from a single provider lookup."""

import http.client
import json
import re
import subprocess
import time
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from clash_sub import bandwagon
from clash_sub.online import LIMIT, read_token
from clash_sub.template_sync import _write_file_atomically
from clash_sub.xui import read_panel_settings

UNITS = Path('/etc/systemd/system')
TIMER = 'clash-sub-inbound-reset.timer'
MARKER = '# Generated by clash-sub for monthly inbound resets.\n'


class ScheduleError(ValueError):
    """A credential-free diagnostic suitable for the terminal."""


def calendar_rules(reset):
    day = reset.day
    dates = ['*-*-%02d' % day]
    if day >= 29:
        # February's last day also matches the ordinary rule in leap years
        # for day 29. systemd coalesces simultaneous calendar events.
        dates.append('*-02~01')
    if day == 31:
        dates.append('*-04,06,09,11~01')
    return ['OnCalendar=%s %s Asia/Shanghai' % (date, reset.strftime('%H:%M:%S'))
            for date in dates]


def configure(confirm, *, units=UNITS, runner=subprocess.run):
    credentials = bandwagon.load_credentials()
    if credentials is None:
        raise ScheduleError('请先设置搬瓦工 API 凭据')
    try:
        read_token()
    except (OSError, KeyError, ValueError):
        raise ScheduleError('请先在菜单 4 → 8 设置有客户端和入站重置权限的 3x-ui 令牌') from None
    try:
        timestamp = bandwagon.query_usage(*credentials)['next_reset']
    except ValueError:
        raise ScheduleError('读取搬瓦工重置时间失败，请在菜单中验证 API 配置') from None
    if timestamp <= time.time():
        raise ScheduleError('搬瓦工返回的下次重置时间已过，请稍后再试')
    reset = datetime.fromtimestamp(timestamp, ZoneInfo('Asia/Shanghai'))
    schedule = '每月 %d 日 %s（北京时间）' % (reset.day, reset.strftime('%H:%M:%S'))
    if reset.day > 28:
        schedule += '，短月取月末'
    if not confirm('%s清零所有 3x-ui 客户端及入站的上下行累计。下次 %s。确认设置？[y/N] ' %
                   (schedule, reset.strftime('%Y-%m-%d %H:%M:%S'))):
        return '已取消。'
    timer = (MARKER + '[Unit]\nDescription=Monthly 3x-ui inbound traffic reset\n'
             '[Timer]\n' + '\n'.join(calendar_rules(reset)) +
             '\nAccuracySec=1s\n[Install]\nWantedBy=timers.target\n')
    timer_path = units / TIMER
    if timer_path.is_symlink() or (timer_path.exists() and not timer_path.is_file()):
        raise ScheduleError('同名路径不是普通定时器文件，请检查 systemd 配置')
    previous = timer_path.read_bytes() if timer_path.exists() else None
    if previous is not None and not previous.startswith(MARKER.encode()):
        raise ScheduleError('存在同名的非托管定时器，请检查 systemd 配置')
    active = enabled = False
    if previous is not None:
        active = runner(['systemctl', 'is-active', '--quiet', TIMER], check=False).returncode == 0
        enabled = runner(['systemctl', 'is-enabled', '--quiet', TIMER], check=False).returncode == 0
    _write_file_atomically(timer_path, timer.encode(), 0o644)
    try:
        runner(['systemctl', 'daemon-reload'], check=True)
        runner(['systemctl', 'enable', TIMER], check=True)
        runner(['systemctl', 'restart', TIMER], check=True)
    except (OSError, subprocess.CalledProcessError):
        if not active:
            runner(['systemctl', 'stop', TIMER], check=False)
        if not enabled:
            runner(['systemctl', 'disable', TIMER], check=False)
        if previous is None:
            timer_path.unlink()
        else:
            _write_file_atomically(timer_path, previous, 0o644)
        runner(['systemctl', 'daemon-reload'], check=True)
        if active:
            runner(['systemctl', 'restart', TIMER], check=True)
        raise
    return '已设置%s重置客户端及入站流量。请关闭 3x-ui 客户端及入站原有的自动重置，避免重复清零。' % schedule


def reset_inbounds(database):
    port, base, _ = read_panel_settings(database)
    token = read_token()
    failures = []
    for scope in ('clients', 'inbounds'):
        connection = http.client.HTTPConnection('127.0.0.1', port, timeout=10)
        try:
            connection.request('POST', base + 'panel/api/%s/resetAllTraffics' % scope, body=b'',
                               headers={'Authorization': 'Bearer ' + token, 'Accept': 'application/json'})
            response = connection.getresponse()
            if response.status != 200:
                raise ValueError('traffic_reset_failed')
            data = response.read(LIMIT + 1)
            if len(data) > LIMIT:
                raise ValueError('traffic_reset_failed')
            payload = json.loads(data)
            if not isinstance(payload, dict) or payload.get('success') is not True:
                raise ValueError('traffic_reset_failed')
        except (OSError, ValueError, http.client.HTTPException):
            failures.append(scope)
        finally:
            connection.close()
    if failures:
        raise ValueError('traffic_reset_failed_' + '_'.join(failures))


def scheduled_reset_label(units=UNITS, *, compact=False):
    """Read the installed monthly schedule for the personal usage page."""
    try:
        text = (units / TIMER).read_text(encoding='utf-8')
    except OSError:
        return '未设置定时重置'
    if not text.startswith(MARKER):
        return '定时重置时间待确认'
    match = re.search(
        r'^OnCalendar=\*-\*-(\d{2}) (\d{2}:\d{2}:\d{2}) Asia/Shanghai$', text, re.MULTILINE)
    if match is None:
        return '定时重置时间待确认'
    day = int(match[1])
    try:
        datetime.strptime(match[2], '%H:%M:%S')
        if not 1 <= day <= 31:
            raise ValueError('invalid_day')
    except ValueError:
        return '定时重置时间待确认'
    display_time = match[2][:5] if compact else match[2] + '（北京时间）'
    label = '每月 %d 日 %s' % (day, display_time)
    if day > 28:
        label += '（短月取月末）'
    return label
